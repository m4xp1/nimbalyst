#!/usr/bin/env node
// Generates the wiki skills twice from one source: the desktop copy the
// knowledge extension hands to its agents (the `wiki` plugin, /wiki:setup and
// /wiki:update), and the copy in the standalone `nimbalyst-wiki` Claude Code
// plugin (/nimbalyst-wiki:setup and /nimbalyst-wiki:update), which
// runs against the remote wiki tools on the sync server. Tool names and arguments are the same on both
// sides (collab-protocol `pageToolContract.ts`), so the source differs only in
// marked passages:
//
//   <!-- desktop-only -->  ... <!-- /desktop-only -->   Personal pages, drafts, session citations
//   <!-- remote-only -->   ... <!-- /remote-only -->    pages_status first, terminal citations
//   <!-- local-only -->    ... <!-- /local-only -->     the plugin's local wiki (nimbalyst-local server)
//
// Local blocks are part of the plugin copy (the remote side), which serves both
// the team wiki and the local one; the desktop drops them, since the app reaches
// its local wiki through its own tools.
//
// Each side keeps its own blocks and drops the other's, so neither copy shows
// the other side's text to its model (the desktop loads its skills raw, HTML
// comments included). Then every tool a copy names must exist on that side: a
// desktop-only tool outside a desktop-only block fails the build, as does a
// terminal-only tool outside a remote-only block.
//
// Also writes the plugin's .mcp.json, .codex-mcp.json and hooks/hooks.json. The
// fork defaults to bundled local servers/hooks, preserving its own search.
// An explicit published distribution retains the upstream npm config generator.
//
//   node scripts/build-wiki-plugin.mjs          write both copies and the plugin configs
//   node scripts/build-wiki-plugin.mjs --check  exit 1 if any generated file is stale

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';
import { PAGE_TOOL_CONTRACT } from '../packages/collab-protocol/src/pageToolContract.ts';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_LABEL = 'packages/extensions/knowledge/skills-source';
export const DEFAULT_SOURCE = path.join(REPO_ROOT, SOURCE_LABEL);
export const DEFAULT_TARGETS = {
  desktop: path.join(REPO_ROOT, 'packages/extensions/knowledge/claude-plugin/skills'),
  remote: path.join(REPO_ROOT, 'plugins/nimbalyst-wiki/skills'),
};
export const SESSION_HELPER_ENTRY = path.join(REPO_ROOT, 'packages/extensions/knowledge/src/sessionInputs/pluginEntry.ts');
export const SESSION_HELPER_OUT = path.join(REPO_ROOT, 'plugins/nimbalyst-wiki/scripts/session-inputs.mjs');
export const LOCAL_SERVER_ENTRY = path.join(REPO_ROOT, 'packages/cli/src/mcp/pluginBundledEntry.ts');
export const LOCAL_SERVER_OUT = path.join(REPO_ROOT, 'plugins/nimbalyst-wiki/scripts/nim-local-mcp.mjs');
export const WIKI_CONTEXT_ENTRY = path.join(REPO_ROOT, 'packages/cli/src/mcp/wikiContextEntry.ts');
export const WIKI_CONTEXT_OUT = path.join(REPO_ROOT, 'plugins/nimbalyst-wiki/scripts/wiki-context.mjs');
export const PLUGIN_DIR = path.join(REPO_ROOT, 'plugins/nimbalyst-wiki');
/**
 * The add-on that declares the `nimbalyst-team` HTTP server. It is a plugin of
 * its own so a local-only user never sees a sign-in prompt; the `team` skill
 * installs it. Hand-written: manifests and MCP config only, no skills.
 */
export const TEAM_PLUGIN_DIR = path.join(REPO_ROOT, 'plugins/nimbalyst-wiki-team');
export const SIDES = ['desktop', 'remote'];
/**
 * Source skill directory -> the skill's directory and `name` on each side. The
 * names match today (/wiki:setup and /nimbalyst-wiki:setup); only the plugin
 * namespace differs.
 */
export const GENERATED_SKILLS = {
  setup: { desktop: 'setup', remote: 'setup' },
  update: { desktop: 'update', remote: 'update' },
};

const GENERATED_NOTE = `GENERATED by scripts/build-wiki-plugin.mjs from ${SOURCE_LABEL}. Do not edit; edit the source and re-run the script.`;

/** The plugin's local stdio helper: the terminal user's own prompts and answers. */
export const SESSION_INPUTS_TOOL = 'list_session_inputs';

/** The `nimbalyst-local` server's tools outside the shared contract. */
export const LOCAL_INIT_TOOL = 'initLocalWiki';
export const LOCAL_CONVERT_TOOL = 'convertTypeStorage';
export const LOCAL_SERVE_TOOL = 'openWikiInBrowser';
export const LOCAL_COVERAGE_TOOL = 'pagesForFiles';
export const LOCAL_DOCTOR_TOOL = 'wikiDoctor';
export const LOCAL_MARKS_TOOL = 'listMarks';

/** Every tool the remote server offers, plus the plugin's local servers. */
const REMOTE_TOOLS = new Set([...PAGE_TOOL_CONTRACT.map((tool) => tool.name), SESSION_INPUTS_TOOL, LOCAL_INIT_TOOL, LOCAL_CONVERT_TOOL, LOCAL_SERVE_TOOL, LOCAL_COVERAGE_TOOL, LOCAL_DOCTOR_TOOL, LOCAL_MARKS_TOOL]);
/** Tools only a terminal agent has. */
const TERMINAL_ONLY_TOOLS = new Set([
  ...PAGE_TOOL_CONTRACT.filter((tool) => tool.availability === 'remoteOnly').map((tool) => tool.name),
  SESSION_INPUTS_TOOL,
  LOCAL_INIT_TOOL,
  LOCAL_CONVERT_TOOL,
  LOCAL_SERVE_TOOL,
  LOCAL_COVERAGE_TOOL,
  LOCAL_DOCTOR_TOOL,
  LOCAL_MARKS_TOOL,
]);
/**
 * Desktop agent tools a skill could name that the remote server does not
 * offer. `tracker_*` and `mcp__*` names are caught by shape, so only the
 * camelCase ones need listing.
 */
const DESKTOP_TOOLS = [
  'readCollabDocComments',
  'createCollabDocComment',
  'replyToCollabDocComment',
  'getResourceSharingStatus',
  'declareCanvasWorkingSet',
  'releaseCanvasWorkingSet',
  'importFileToPages',
  'capture_editor_screenshot',
  'developer_git_commit_proposal',
  'get_session_edited_files',
  'work_radar',
];
const TOOL_REFERENCE = new RegExp(
  `mcp__[\\w-]+|(?<![\\w-])(?:(?:tracker|wiki|pages)_[a-z]+(?:_[a-z]+)*|${[...DESKTOP_TOOLS, ...TERMINAL_ONLY_TOOLS].join('|')})(?![\\w-])`,
  'g',
);

/** Tool names in `text` the given side does not have. */
export function checkToolNames(text, side) {
  const found = new Set(text.match(TOOL_REFERENCE) ?? []);
  const unknown = side === 'remote' ? [...found].filter((name) => !REMOTE_TOOLS.has(name)) : [...found].filter((name) => TERMINAL_ONLY_TOOLS.has(name));
  return unknown;
}

const BLOCK = {
  desktop: /<!-- desktop-only -->\r?\n([\s\S]*?)<!-- \/desktop-only -->\r?\n/g,
  remote: /<!-- remote-only -->\r?\n([\s\S]*?)<!-- \/remote-only -->\r?\n/g,
  local: /<!-- local-only -->\r?\n([\s\S]*?)<!-- \/local-only -->\r?\n/g,
};
const STRAY_MARKER = /<!-- \/?(?:desktop|remote|local)-only\b/;

/** `text` as `side` sees it: its own blocks unwrapped, the other side's dropped. */
export function applyBranch(text, side, fileLabel = '<text>') {
  text = text.replace(/\r\n/g, '\n'); // Git's Windows checkout may use CRLF. Generated text is canonical LF.
  if (!text.includes('-only')) return text;
  const other = side === 'desktop' ? 'remote' : 'desktop';
  const out = text
    .replace(BLOCK[other], '')
    .replace(BLOCK[side], '$1')
    .replace(BLOCK.local, side === 'remote' ? '$1' : '')
    // A dropped block between two paragraphs leaves both blank lines behind.
    .replace(/\n{3,}/g, '\n\n');
  if (STRAY_MARKER.test(out)) throw new Error(`${fileLabel}: unbalanced desktop-only/remote-only/local-only marker`);
  return out;
}

function injectSkillHeader(text, fileLabel) {
  const match = /^---\r?\n[\s\S]*?\r?\n---\r?\n/.exec(text);
  if (!match) throw new Error(`${fileLabel}: SKILL.md has no frontmatter`);
  const frontmatter = match[0];
  const body = text.slice(frontmatter.length).replace(/^\n+/, '');
  const referencesNote = 'Its references/ files are generated from the same source.';
  return `${frontmatter}\n<!-- ${GENERATED_NOTE} ${referencesNote} -->\n\n${body}`;
}

/** The slash command each side's plugin namespace gives a skill. */
const PLUGIN_NAMESPACE = { desktop: 'wiki', remote: 'nimbalyst-wiki' };

/**
 * Points the frontmatter `name`, `../<skill>/` cross-references and
 * `/wiki:<skill>` commands at the side's skill names. The source is written
 * as the desktop sees it.
 */
export function renameSkills(text, side) {
  let out = text;
  for (const [source, names] of Object.entries(GENERATED_SKILLS)) {
    out = out.replaceAll(`/${PLUGIN_NAMESPACE.desktop}:${source}\``, `/${PLUGIN_NAMESPACE[side]}:${names[side]}\``);
    if (names[side] === source) continue;
    out = out
      .replace(new RegExp(`^(---\\nname: )${source}\\n`), `$1${names[side]}\n`)
      .replaceAll(`../${source}/`, `../${names[side]}/`);
  }
  return out;
}

function transformFile(relPath, text, side) {
  const label = `${relPath} (${side})`;
  const branched = renameSkills(applyBranch(text, side, label), side);
  const unknown = checkToolNames(branched, side);
  if (unknown.length > 0) {
    const fence = side === 'remote' ? 'desktop-only' : 'remote-only';
    throw new Error(`${label}: names ${unknown.join(', ')}, which the ${side} agent does not have; put it in a <!-- ${fence} --> block`);
  }
  if (path.basename(relPath) === 'SKILL.md') return injectSkillHeader(branched, label);
  if (/\.ya?ml$/.test(relPath)) return `# ${GENERATED_NOTE}\n${branched}`;
  // Other references (wiki-guide.md) are copied verbatim into pages by the
  // setup skill, so a header here would end up in the team's guide page. The
  // owning SKILL.md carries the generated marker for them.
  return branched;
}

export function listFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? listFiles(full, base) : [path.relative(base, full).split(path.sep).join('/')];
  });
}

/** Returns Map<`<side>:<path under skills/>`, generated content>. */
export function buildGeneratedFiles(sourceDir = DEFAULT_SOURCE) {
  const files = new Map();
  for (const [skill, names] of Object.entries(GENERATED_SKILLS)) {
    const skillDir = path.join(sourceDir, skill);
    const rels = listFiles(skillDir).sort();
    if (!rels.includes('SKILL.md')) throw new Error(`${skill}: missing SKILL.md in ${skillDir}`);
    for (const rel of rels) {
      const relPath = `${skill}/${rel}`;
      const text = readFileSync(path.join(skillDir, rel), 'utf8').replace(/\r\n/g, '\n');
      for (const side of SIDES) files.set(`${side}:${names[side]}/${rel}`, transformFile(relPath, text, side));
    }
  }
  return files;
}

/** The npm package the plugin runs, pinned to the plugin's version. */
export function cliSpec(pluginDir = PLUGIN_DIR) {
  return `@nimbalyst/cli@${JSON.parse(readFileSync(path.join(pluginDir, '.claude-plugin/plugin.json'), 'utf8')).version}`;
}

/**
 * The plugin's server and hook configs, path relative to the plugin to content.
 * Both agents start servers in the project. Claude Code passes the plugin root;
 * Codex expands no variables in MCP args (and npx would replace a forwarded
 * `PWD`), so it says `--plugin-agent codex` and the server finds its install
 * by version (packages/cli/src/mcp/pluginEntry.ts). Codex runs no plugin hooks.
 *
 * `--prefix /` keeps npx from running a copy of the CLI in the project's own
 * node_modules at the same version (this monorepo links packages/cli there, so
 * a stale local build ran instead of the published one). The command still
 * runs in the project folder.
 */
export function buildPluginConfigs(pluginDir = PLUGIN_DIR, { distribution = 'bundled' } = {}) {
  const spec = cliSpec(pluginDir);
  const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
  // The fork keeps its own lexical matching; the public npm CLI cannot supply it.
  if (distribution === 'bundled') {
    const root = '${CLAUDE_PLUGIN_ROOT}';
    const command = (verb) => ({ hooks: [{ type: 'command', command: `node "${root}/scripts/wiki-context.mjs" ${verb}`, timeout: 10 }] });
    return new Map([
      ['.mcp.json', json({ mcpServers: {
        'nimbalyst-session': { type: 'stdio', command: 'node', args: [`${root}/scripts/session-inputs.mjs`] },
        'nimbalyst-local': { type: 'stdio', command: 'node', args: [`${root}/scripts/nim-local-mcp.mjs`] },
      } })],
      ['.codex-mcp.json', json({ mcpServers: {
        'nimbalyst-session': { command: 'node', cwd: '.', env_vars: ['PWD'], args: ['./scripts/session-inputs.mjs'] },
        'nimbalyst-local': { command: 'node', cwd: '.', env_vars: ['PWD', 'CODEX_HOME'], args: ['./scripts/nim-local-mcp.mjs'] },
      } })],
      ['hooks/hooks.json', json({ description: 'Local fork wiki hooks, built from the current CLI source without an npm download.',
        hooks: { SessionStart: [command('session-start')], Stop: [command('stop')] } })],
    ]);
  }
  const npx = (...args) => ['--prefix', '/', '-y', spec, ...args];
  const hook = (verb) => ({ hooks: [{ type: 'command', command: ['npx', ...npx('hook', verb)].join(' '), timeout: 30 }] });
  return new Map([
    ['.mcp.json', json({
      mcpServers: {
        'nimbalyst-session': { type: 'stdio', command: 'npx', args: npx('hook', 'session-inputs') },
        'nimbalyst-local': { type: 'stdio', command: 'npx', args: npx('mcp', '--plugin-root', '${CLAUDE_PLUGIN_ROOT}') },
      },
    })],
    ['.codex-mcp.json', json({
      mcpServers: {
        'nimbalyst-session': { command: 'npx', args: npx('hook', 'session-inputs') },
        // Codex passes servers a filtered environment; a custom CODEX_HOME is where the server finds its install.
        'nimbalyst-local': { command: 'npx', env_vars: ['CODEX_HOME'], args: npx('mcp', '--plugin-agent', 'codex') },
      },
    })],
    ['hooks/hooks.json', json({
      description: 'At session start, tell the agent what the project\'s local wiki covers. Once per session, after substantive work, ask the agent to record what it decided in the wiki. Both run the pinned @nimbalyst/cli through npx; the first run downloads it.',
      // A first run downloads the package; a hook past its timeout fails open.
      hooks: { SessionStart: [hook('session-start')], Stop: [hook('stop')] },
    })],
  ]);
}

export function bundleSessionHelper() {
  const result = buildSync({
    absWorkingDir: REPO_ROOT,
    entryPoints: [path.relative(REPO_ROOT, SESSION_HELPER_ENTRY)],
    bundle: true,
    write: false,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    alias: {
      '@nimbalyst/collab-protocol': './packages/collab-protocol/src/index.ts',
      '@nimbalyst/runtime/core/citationSyntax': './packages/runtime/src/core/citationSyntax.ts',
    },
    banner: { js: `#!/usr/bin/env node\n// ${GENERATED_NOTE.replace(SOURCE_LABEL, 'packages/extensions/knowledge/src/sessionInputs')}` },
    legalComments: 'none',
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

/**
 * `nim mcp` (or another entry from packages/cli, such as the SessionStart hook)
 * as one ESM file. better-sqlite3 stays external: the wiki tools never load it,
 * and a plugin has no native modules to load.
 */
export function bundleLocalServer(entry = LOCAL_SERVER_ENTRY) {
  const cliPackage = JSON.parse(readFileSync(path.join(REPO_ROOT, 'packages/cli/package.json'), 'utf8'));
  const result = buildSync({
    absWorkingDir: REPO_ROOT,
    entryPoints: [path.relative(REPO_ROOT, entry)],
    bundle: true,
    write: false,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ['better-sqlite3'],
    define: { __NIM_VERSION__: JSON.stringify(cliPackage.version) },
    alias: {
      '@nimbalyst/tracker-core': './packages/tracker-core/src/index.ts',
      '@nimbalyst/wiki-plugin/session-inputs': './packages/extensions/knowledge/src/sessionInputs/server.ts',
      '@nimbalyst/local-wiki': './packages/local-wiki/src/index.ts',
      '@nimbalyst/collab-protocol': './packages/collab-protocol/src/index.ts',
      // The app's mark parser; see packages/cli/src/types/pageMarkSyntax.d.ts.
      '@nimbalyst/runtime/core/pageMarkSyntax': './packages/runtime/src/core/pageMarkSyntax.ts',
    },
    banner: { js: `#!/usr/bin/env node\n// ${GENERATED_NOTE.replace(SOURCE_LABEL, 'packages/cli/src/mcp')}` },
    legalComments: 'none',
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

/** The bundled files, output path to generator. */
const BUNDLES = [
  [SESSION_HELPER_OUT, () => bundleSessionHelper()],
  [LOCAL_SERVER_OUT, () => bundleLocalServer()],
  [WIKI_CONTEXT_OUT, () => bundleLocalServer(WIKI_CONTEXT_ENTRY)],
  // The generated CLI bundles include the existing Russian search package.
  // Ship its unmodified source and BSD notice with the plugin as with the desktop app.
  ...['COPYING', 'SOURCE.md', 'base-stemmer.js', 'russian-stemmer.js'].map(name => [
    path.join(PLUGIN_DIR, 'scripts', 'snowball-russian-3.1.1', name),
    () => readFileSync(path.join(REPO_ROOT, 'packages/search-text/src/snowball', name), 'utf8'),
  ]),
];

function outputSkills(side) {
  return Object.values(GENERATED_SKILLS).map((names) => names[side]);
}

function targetPath(targets, key) {
  const [side, relPath] = [key.slice(0, key.indexOf(':')), key.slice(key.indexOf(':') + 1)];
  return path.join(targets[side], relPath);
}

/** Lists generated paths that are missing, different, or no longer produced. */
export function checkGenerated({ sourceDir = DEFAULT_SOURCE, targets = DEFAULT_TARGETS, configs = true, pluginDir = PLUGIN_DIR, bundle = sourceDir === DEFAULT_SOURCE, distribution = 'bundled' } = {}) {
  const expected = buildGeneratedFiles(sourceDir);
  const stale = [];
  for (const [key, content] of expected) {
    const onDisk = targetPath(targets, key);
    if (!existsSync(onDisk)) stale.push(`missing: ${key}`);
    else if (readFileSync(onDisk, 'utf8').replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) stale.push(`changed: ${key}`);
  }
  for (const side of SIDES) {
    for (const skill of outputSkills(side)) {
      for (const rel of listFiles(path.join(targets[side], skill))) {
        if (!expected.has(`${side}:${skill}/${rel}`)) stale.push(`extra: ${side}:${skill}/${rel}`);
      }
    }
  }
  if (bundle) {
    for (const [out, generate] of BUNDLES) {
      const rel = path.relative(REPO_ROOT, out);
      if (!existsSync(out)) stale.push(`missing: ${rel}`);
      else if (readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== generate().replace(/\r\n/g, '\n')) stale.push(`changed: ${rel}`);
    }
  }
  if (configs) {
    for (const [rel, content] of buildPluginConfigs(pluginDir, { distribution })) {
      const out = path.join(pluginDir, rel);
      const label = path.relative(REPO_ROOT, out);
      if (!existsSync(out)) stale.push(`missing: ${label}`);
      else if (readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) stale.push(`changed: ${label}`);
    }
  }
  return stale;
}

/**
 * The plugin's Claude Code and Codex manifests must carry one version: each
 * agent's install reads its own, the generated configs pin `@nimbalyst/cli` to
 * it, and the update check in the local server compares against the published one (packages/cli/src/mcp/updateCheck.ts).
 * The team add-on carries the same version, since that check only reads
 * nimbalyst-wiki's manifest.
 */
export function checkManifestVersions(pluginDir = PLUGIN_DIR, teamDir = TEAM_PLUGIN_DIR, cliDir = pluginDir === PLUGIN_DIR ? path.join(REPO_ROOT, 'packages/cli') : null) {
  const read = (root, dir) => {
    const file = path.join(root, dir, 'plugin.json');
    return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')).version : undefined;
  };
  const problems = [];
  for (const [root, prefix] of [[pluginDir, ''], [teamDir, 'nimbalyst-wiki-team: ']]) {
    const claude = read(root, '.claude-plugin');
    const codex = read(root, '.codex-plugin');
    if (claude !== codex) problems.push(`${prefix}version mismatch: .claude-plugin/plugin.json is ${claude}, .codex-plugin/plugin.json is ${codex}`);
  }
  const plugin = read(pluginDir, '.claude-plugin');
  const team = read(teamDir, '.claude-plugin');
  if (team !== plugin) problems.push(`version mismatch: nimbalyst-wiki-team is ${team}, nimbalyst-wiki is ${plugin}`);
  // The plugin runs @nimbalyst/cli@<its version>, so the two are released together.
  if (cliDir) {
    const cli = JSON.parse(readFileSync(path.join(cliDir, 'package.json'), 'utf8')).version;
    if (cli !== plugin) problems.push(`version mismatch: nimbalyst-wiki is ${plugin}, packages/cli is ${cli}; the plugin runs @nimbalyst/cli@${plugin}`);
  }
  return problems;
}

export function writeGenerated({ sourceDir = DEFAULT_SOURCE, targets = DEFAULT_TARGETS, configs = true, bundle = sourceDir === DEFAULT_SOURCE, distribution = 'bundled' } = {}) {
  const files = buildGeneratedFiles(sourceDir);
  // Only the generated skill directories are replaced; hand-written skills
  // (the plugin's `connect`) live beside them and are never touched.
  for (const side of SIDES) {
    for (const skill of outputSkills(side)) rmSync(path.join(targets[side], skill), { recursive: true, force: true });
  }
  for (const [key, content] of files) {
    const out = targetPath(targets, key);
    mkdirSync(path.dirname(out), { recursive: true });
    writeFileSync(out, content);
  }
  const written = [...files.keys()];
  if (bundle) {
    for (const [out, generate] of BUNDLES) {
      mkdirSync(path.dirname(out), { recursive: true });
      writeFileSync(out, generate(), { mode: 0o755 });
      written.push(path.relative(REPO_ROOT, out));
    }
  }
  if (configs) {
    for (const [rel, content] of buildPluginConfigs(PLUGIN_DIR, { distribution })) {
      const out = path.join(PLUGIN_DIR, rel);
      mkdirSync(path.dirname(out), { recursive: true });
      writeFileSync(out, content);
      written.push(path.relative(REPO_ROOT, out));
    }
  }
  return written;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = [...checkGenerated(), ...checkManifestVersions()];
    if (stale.length > 0) {
      console.error(`Generated wiki skills are stale:\n  ${stale.join('\n  ')}\nRun: node scripts/build-wiki-plugin.mjs`);
      process.exit(1);
    }
    console.log('Generated wiki skills and the plugin configs are up to date.');
  } else {
    const written = writeGenerated();
    console.log(`Wrote ${written.length} files.`);
  }
}
